-- Execute once in the Supabase SQL Editor before deploying this backend.
BEGIN;
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS credenciales_version INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE REFERENCES public.usuarios(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_vencimiento TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_vencimiento TIMESTAMPTZ NOT NULL,
    fecha_uso TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_password_reset_usuario ON public.password_reset_tokens(usuario_id);
-- Only the trusted Spring backend DB connection should access these hashes.
ALTER TABLE public.refresh_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.refresh_tokens, public.password_reset_tokens FROM anon, authenticated;
COMMIT;
